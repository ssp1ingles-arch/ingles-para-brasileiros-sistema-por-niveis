import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
const raiz = path.resolve(import.meta.dirname, '..');
const fonteRaiz = process.env.ARQUIVO_FONTE_DIR || path.resolve(import.meta.dirname, '../../Arquivo_Fonte');
const ler = arquivo => JSON.parse(fs.readFileSync(path.join(raiz, arquivo), 'utf8'));
const triagem = ler('dados/lote-025-triagem.json');
const mapa = ler('dados/mapeamento-fontes-extensas-025.json');
const unidades = ['a1','a2','b1','b2','c1','c2','kids'].flatMap(n => ler(`dados/${n}/unidades.json`));
const fonte = mapa.fontes[0];
const resultados = [];
function validar(teste, condicao, detalhe = '') { resultados.push({ teste, resultado: condicao ? 'APROVADO' : 'FALHOU', detalhe }); if (!condicao) throw new Error(`${teste}: ${detalhe}`); }
validar('1188 lida e aplicada', triagem.sequenciais[0].numero === 1188 && triagem.sequenciais[0].status === 'sem conteúdo didático' && mapa.regras_aplicadas.length === 4);
validar('1189 aberta somente após regras', triagem.intervalo.join(',') === '1188,1189');
validar('1189 361 páginas presentes', fonte.paginas.length === 361 && fonte.totais.presentes === 361);
validar('página 2 ausente registrada', fonte.paginacao.ausentes.join(',') === '2' && !fonte.paginacao.continua);
validar('todas as páginas decididas', fonte.paginas.every(x => ['consolidar','descartar'].includes(x.decisao)));
validar('nenhuma seção útil sem destino', fonte.sem_destino_util === 0);
validar('destinos específicos existentes', fonte.paginas.filter(x => x.unidade_relacionada).every(x => unidades.some(u => u.id === x.unidade_relacionada)));
validar('categorias editoriais separadas', fonte.totais.editoriais === 8 && fonte.totais.indices === 8);
validar('zero corrupção detectada', fonte.totais.corrompidas === 0);
validar('nenhuma página ou exemplo republicado', !JSON.stringify(mapa).includes('exemplos_aproveitados') && fonte.observacao_direitos.includes('não são republicados'));
validar('1190 ainda bloqueada', !triagem.sequenciais.some(x => x.numero === 1190) && mapa.comparacoes_integrais.length === 0);
const meta = ler('dados/mapa-fontes.json').arquivos.find(x => Number(x.id) === 1189);
const hash = crypto.createHash('sha256').update(fs.readFileSync(path.join(fonteRaiz, meta.arquivo))).digest('hex');
validar('hash 1189 preservado', hash === fonte.hash_bruto);
const saida = { total: resultados.length, aprovados: resultados.filter(x => x.resultado === 'APROVADO').length, resultados };
fs.mkdirSync(path.join(raiz, 'docs/evidencias/lote-025'), { recursive: true });
fs.writeFileSync(path.join(raiz, 'docs/evidencias/lote-025/resultados-intermediarios-1189.json'), JSON.stringify(saida, null, 2) + '\n');
console.log(`INTERMEDIÁRIA 1189: ${saida.aprovados}/${saida.total}`);
