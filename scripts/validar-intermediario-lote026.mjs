ok('sem reprodução extensa', !JSON.stringify(m).includes('conteudo_fonte') && f.observacao_publica.includes('nenhuma página'));
ok('IDs e base preservados', new Set(u.map(x => x.id)).size === 834 && new Set(a.map(x => x.id)).size === 1977);
ok('Jornada preservada', j.totais.presentes === 806 && j.totais.complementares === 28);
ok('95 subpainéis', s.length === 95);
ok('Kids e C2 válidos', l('dados/kids/unidades.json').every(x => x.nivel_cefr) && l('dados/c2/unidades.json').every(x => x.justificativa_c2));
const meta = l('dados/mapa-fontes.json').arquivos.find(x => +x.id === 1191);
const hash = crypto.createHash('sha256').update(fs.readFileSync(path.join(src, meta.arquivo))).digest('hex');
ok('hash 1191 preservado', hash === f.hash_bruto);
ok('1192 ainda bloqueada', m.comparacoes_integrais.length === 0 && t.validacao_intermediaria.pendente);
const z = { total: out.length, aprovados: out.filter(x => x.resultado === 'APROVADO').length, resultados: out };
fs.mkdirSync(path.join(r, 'docs/evidencias/lote-026'), { recursive: true });
fs.writeFileSync(path.join(r, 'docs/evidencias/lote-026/resultados-intermediarios-1191.json'), JSON.stringify(z, null, 2) + '\n');
console.log(`INTERMEDIÁRIA 1191: ${z.aprovados}/${z.total}`);
