import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
const r = path.resolve(import.meta.dirname, '..');
const src = process.env.ARQUIVO_FONTE_DIR || path.resolve(import.meta.dirname, '../../Arquivo_Fonte');
const l = a => JSON.parse(fs.readFileSync(path.join(r, a), 'utf8'));
const t = l('dados/lote-026-triagem.json');
const m = l('dados/mapeamento-fontes-extensas-026.json');
const u = ['a1','a2','b1','b2','c1','c2','kids'].flatMap(n => l(`dados/${n}/unidades.json`));
const a = l('dados/atividades.json'), j = l('dados/auditoria-cobertura-jornada-025.json');
const s = l('dados/subpaineis.json'), f = m.fontes[0], out = [];
function ok(teste, valor, detalhe = '') { out.push({ teste, resultado: valor ? 'APROVADO' : 'FALHOU', detalhe }); if (!valor) throw Error(`${teste}: ${detalhe}`); }
ok('somente 1191 aberta', t.intervalo.join(',') === '1191,1191' && t.sequenciais.length === 1 && m.fontes.length === 1 && f.numero === 1191 && m.comparacoes_integrais.length === 0);
ok('leitura integral', f.leitura_integral && f.paginas.length === 361 && f.secoes.length === 78);
ok('página 2 ausente registrada', f.paginacao.ausentes.join(',') === '2');
ok('sem páginas repetidas', !f.paginacao.repetidas.length);
ok('sem páginas vazias/OCR/corrupção', !f.paginacao.sem_texto.length && !f.paginacao.ocr_insuficiente.length && !f.paginacao.corrompidas.length);
ok('todas as páginas decididas', f.paginas.every(x => ['consolidar em unidade existente','referenciar sem publicar','descartar'].includes(x.decisao)));
ok('nenhum conteúdo útil sem destino', f.totais.uteis_sem_destino === 0);
ok('destinos existentes', f.paginas.filter(x => x.destino_especifico).every(x => u.some(y => y.id === x.destino_especifico)));
ok('editorial justificado', f.paginas.filter(x => x.categoria.includes('editorial') || x.categoria.includes('capa')).every(x => x.decisao === 'descartar' && x.justificativa));
